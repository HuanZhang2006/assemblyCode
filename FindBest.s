.data
# 测试数据：长度为 7 的整数数组
array:
    .word   12, -45, 93219, 0, -1232913, 888, 54

.text
.globl main

main:
    # 1. 准备传入 find_best 的参数
    la      a0, array           # a0: 数组首地址
    li      a1, 7               # a1: 数组长度
    la      a2, largest         # a2: 比较器函数指针（亦可替换为 smallest 测试）

    # 2. 调用 find_best
    jal     ra, find_best

    # 运行结束后，返回值保存在 a0 中
    # 系统调用退出（模拟器环境退出）
    li      a7, 10
    ecall


# ==============================================================================
# find_best:
#   在数组中根据比较器逻辑寻找最优元素
#   参数:
#     a0: 数组首地址
#     a1: 数组长度
#     a2: 比较器函数指针
#   返回值:
#     a0: 最优值
# ==============================================================================
find_best:
    # --- 1. Prologue: 栈空间分配与 Callee-Saved 寄存器保存 ---
    # 需要保存 ra 以及 s0 ~ s4，共 6 个寄存器 (6 * 4 = 24 字节)
    addi    sp, sp, -24
    sw      ra, 20(sp)
    sw      s0, 16(sp)
    sw      s1, 12(sp)
    sw      s2, 8(sp)
    sw      s3, 4(sp)
    sw      s4, 0(sp)

    # --- 2. 状态与变量初始化 ---
    mv      s1, a0              # s1 = 当前元素内存地址（初始为数组首地址）
    lw      s0, 0(s1)           # s0 = 当前最优值（初始为第一个元素）
    li      s2, 0               # s2 = 当前索引（初始为 0）
    mv      s3, a1              # s3 = 数组长度（防 a1 被子调用覆写）
    mv      s4, a2              # s4 = 比较器函数指针（防 a2 被子调用覆写，课程重点 Bug 修复）

loop_start:
    # --- 3. 准备调用比较器 ---
    # 比较器期望: a0 = 当前最优值, a1 = 当前遍历到的元素
    mv      a0, s0              # 将当前最优值放入 a0
    lw      a1, 0(s1)           # 从 s1 读取当前元素放入 a1

    # 通过函数指针调用比较器（跳转至 s4 存储的地址）
    jalr    ra, 0(s4)

    # --- 4. 处理比较器返回值 ---
    # 约定: 若 a0 优先于 a1，则返回 1；否则返回 0
    # 若返回非 0（即当前 s0 依然更优），则跳过值更新
    bnez    a0, loop_update

    # 若返回 0，说明当前元素更优（或等于），更新最优值
    lw      s0, 0(s1)           # 将当前元素载入 s0 作为新的最优值

loop_update:
    # --- 5. 步进指针与索引 ---
    addi    s1, s1, 4           # s1 指向下一个整数地址 (地址 + 4)
    addi    s2, s2, 1           # 索引 + 1

    # --- 6. 循环条件判断 ---
    blt     s2, s3, loop_start  # 若 s2 < s3 (cur_index < length)，继续循环

loop_end:
    # --- 7. 设置返回值 ---
    mv      a0, s0              # 将最优值放入返回值寄存器 a0

    # --- 8. Epilogue: 寄存器恢复与栈销毁 ---
    lw      s4, 0(sp)
    lw      s3, 4(sp)
    lw      s2, 8(sp)
    lw      s1, 12(sp)
    lw      s0, 16(sp)
    lw      ra, 20(sp)
    addi    sp, sp, 24

    ret                         # 即 jalr zero, 0(ra)


# ==============================================================================
# 叶子比较器 1: largest
#   若 a0 > a1 则返回 1，否则返回 0 (等价于 a1 < a0)
# ==============================================================================
largest:
    slt     a0, a1, a0          # a0 = (a1 < a0) ? 1 : 0
    ret


# ==============================================================================
# 叶子比较器 2: smallest
#   若 a0 < a1 则返回 1，否则返回 0
# ==============================================================================
smallest:
    slt     a0, a0, a1          # a0 = (a0 < a1) ? 1 : 0
    ret